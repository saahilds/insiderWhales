"""Markdown write-up of the baseline event study (committed under docs/results)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import polars as pl

from insider_whales.evaluation.event_study import SUBGROUPS
from insider_whales.evaluation.matched_controls import MIN_ADV, RECENT_DAYS, K

LABEL = (
    "> **Exploratory, survivor-only.** Free yfinance prices only cover companies that still "
    "trade; delisted, acquired and bankrupt issuers are missing. Development period 2015-2020 "
    "(2012-2014 is warm-up); no 2021+ returns were used. Treat every number below as a "
    "description of this sample, not as evidence of a tradable edge."
)


def _p(x: Any, digits: int = 2) -> str:
    if x is None or x != x:
        return "-"
    return f"{100 * x:.{digits}f}%"


def _ci(row: dict, prefix: str) -> str:
    lo, hi = row.get(f"{prefix}ci_low"), row.get(f"{prefix}ci_high")
    if lo is None or hi is None:
        return "-"
    return f"[{_p(lo)}, {_p(hi)}]"


def _headline_table(df: pl.DataFrame, direction: str) -> list[str]:
    out = [
        "| Horizon (sessions) | Events | Issuers | Mean raw | Median raw | "
        "Mean minus SPY | Mean minus sector ETF | Mean minus size ETF | "
        "Mean minus matched controls | 95% CI (controls) | Win rate |",
        "|" + "---|" * 11,
    ]
    for r in df.filter(pl.col("direction") == direction).sort("horizon").iter_rows(named=True):
        out.append(
            f"| {r['horizon']} | {r['n']:,} | {r.get('issuers', 0):,} | {_p(r.get('mean'))} | "
            f"{_p(r.get('median'))} | {_p(r.get('mkt_mean'))} | {_p(r.get('sec_mean'))} | "
            f"{_p(r.get('size_mean'))} | {_p(r.get('exc_mean'))} | {_ci(r, 'exc_')} | "
            f"{_p(r.get('win_rate'), 1)} |"
        )
    return out


def _calendar_table(df: pl.DataFrame, direction: str) -> list[str]:
    out = [
        "| Horizon | Months | Raw monthly mean | t | Minus SPY | t | Minus controls | t |",
        "|" + "---|" * 8,
    ]
    for r in df.filter(pl.col("direction") == direction).sort("horizon").iter_rows(named=True):
        out.append(
            f"| {r['horizon']} | {r['raw_months']} | {_p(r['raw_monthly_mean'])} | "
            f"{r['raw_t']:.1f} | {_p(r['mkt_monthly_mean'])} | {r['mkt_t']:.1f} | "
            f"{_p(r['exc_monthly_mean'])} | {r['exc_t']:.1f} |"
        )
    return out


def _subgroup_table(df: pl.DataFrame, grouping: str, direction: str, horizon: int) -> list[str]:
    out = [
        "| Group | Events | Mean raw | Mean minus SPY | Mean minus controls | 95% CI (controls) |",
        "|---|---|---|---|---|---|",
    ]
    sub = df.filter(
        (pl.col("grouping") == grouping)
        & (pl.col("direction") == direction)
        & (pl.col("horizon") == horizon)
    ).sort("value")
    for r in sub.iter_rows(named=True):
        out.append(
            f"| {r['value']} | {r['n']:,} | {_p(r.get('mean'))} | {_p(r.get('mkt_mean'))} | "
            f"{_p(r.get('exc_mean'))} | {_ci(r, 'exc_')} |"
        )
    return out


def _paths_table(paths: pl.DataFrame, direction: str) -> list[str]:
    out = ["| Day | Signal | Matched controls | SPY |", "|---|---|---|---|"]
    for r in paths.filter(pl.col("direction") == direction).sort("day").iter_rows(named=True):
        out.append(f"| {r['day']} | {_p(r['signal'])} | {_p(r['controls'])} | {_p(r['spy'])} |")
    return out


def render_markdown(result: dict[str, Any], subgroup_horizon: int = 60) -> str:
    events: pl.DataFrame = result["events"]
    n_by = {r["direction"]: r for r in events.group_by("direction").len().iter_rows(named=True)}
    issuers = events["issuer_cik"].n_unique()
    paths = result["paths"]
    n_path = int(paths["events"].max()) if paths.height else 0
    lines = [
        "# Baseline event study: insider purchases and sales (2015-2020)",
        "",
        LABEL,
        "",
        "Generated by `uv run insider-whales event-study`; the sample, benchmarks, controls and "
        "statistics are described below. Event tables are in `data/processed/event_study/` and "
        "the full CSVs are in `reports/event_study/` (both git-ignored).",
        "",
        "## Sample",
        "",
        f"- Events: {events.height:,} open-market insider transactions "
        f"({n_by.get('purchase', {}).get('len', 0):,} purchases, "
        f"{n_by.get('sale', {}).get('len', 0):,} sales) from {issuers:,} issuers.",
        "- Conservative event set only (the plan's `conservative` filter), price series that "
        "passed the Form 4 price-consistency check, first executable session in "
        "2015-01-01 to 2020-12-31.",
        "- Entry at the open of the first executable session after the filing became "
        "available; exit at the close of the session `h` sessions later, using the "
        "split- and dividend-adjusted total-return index. Returns whose exit falls after "
        "2020-12-31 are not computed, so later horizons use fewer events, mostly 2020 ones.",
        "- Sales are reported as the return of the stock after the sale (a negative number "
        "would mean the insider sold before a decline), not as a short-selling result.",
        "",
        "## Adjustments",
        "",
        "- **Minus SPY**: market-adjusted return over the same entry-to-exit window.",
        "- **Minus sector ETF**: SPDR sector ETF chosen from the issuer's current SIC code "
        "(coarse prefix mapping; null for unclassified issuers, and XLRE before 2015-10 and "
        "XLC before 2018-06 do not exist).",
        "- **Minus size ETF**: IWM for micro and small caps, MDY for mid, SPY for large and "
        "mega caps and unknown size.",
        f"- **Minus matched controls**: the {K} nearest stocks of the same universe and sector, "
        f"matched on the session before entry by trailing 60-day return, 60-day volatility, "
        f"252-day drawdown and 20-day dollar volume, with no insider disclosure in the "
        f"previous {RECENT_DAYS} days and at least ${MIN_ADV:,.0f} average daily dollar "
        "volume. Controls use the same entry and exit sessions and are averaged per event.",
        "- Confidence intervals are two-way cluster-robust (issuer and calendar month). "
        "Calendar-time tables average each entry month first and use Newey-West standard errors.",
        "",
    ]
    for direction, title in (("purchase", "Purchases"), ("sale", "Sales")):
        lines += [f"## {title}: headline", "", *_headline_table(result["headline"], direction), ""]
    lines += ["### Same, restricted to tradable events", ""]
    lines += [
        "Tradable means a Form 4 average price of at least $5 and 20-day average dollar "
        "volume of at least $2M before entry.",
        "",
    ]
    for direction, title in (("purchase", "Purchases"), ("sale", "Sales")):
        lines += [f"**{title}**", "", *_headline_table(result["tradable"], direction), ""]
    for direction, title in (("purchase", "Purchases"), ("sale", "Sales")):
        lines += [
            f"## {title}: calendar-time view",
            "",
            *_calendar_table(result["calendar_time"], direction),
            "",
        ]
    lines += [
        f"## Cumulative returns by day since entry ({n_path:,} events with complete paths "
        "for purchases; sales use their own complete-path set)",
        "",
    ]
    for direction, title in (("purchase", "Purchases"), ("sale", "Sales")):
        lines += [f"**{title}**", "", *_paths_table(paths, direction), ""]
    for direction, title in (("purchase", "Purchases"), ("sale", "Sales")):
        lines += [
            f"## {title}: subgroups at {subgroup_horizon} sessions",
            "",
            "Mean returns by group. Groups are descriptive; no multiple-testing correction "
            "has been applied.",
            "",
        ]
        for column, label in SUBGROUPS.items():
            lines += [
                f"### {label}",
                "",
                *_subgroup_table(result["subgroups"], column, direction, subgroup_horizon),
                "",
            ]
    lines += [
        "## Limitations",
        "",
        "- Survivor-only prices: issuers that were delisted, acquired or went dark are missing "
        "and delisting returns are unavailable. This flatters long-horizon results.",
        "- Insider purchases and sales cluster in the same issuers and months; confidence "
        "intervals account for that, but the effective sample is far smaller than the "
        "event count.",
        "- Sector is from the current SIC code, not point in time.",
        "- Controls are matched on dollar volume rather than market capitalisation and only "
        "exclude stocks with an insider disclosure in the prior 90 days.",
        "- No transaction costs, spreads or capacity limits are applied here; that is the "
        "backtest's job.",
        "",
    ]
    return "\n".join(lines)


def write_markdown(result: dict[str, Any], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown(result))
    return path
